CREATE TABLE tb_cadastro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    email VARCHAR(255),
    cpf VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_tb_cadastro_cpf UNIQUE (cpf)
);

CREATE TABLE tb_livros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tb_exemplares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT NOT NULL,
    codigo_patrimonio VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_tb_exemplares_codigo_patrimonio UNIQUE (codigo_patrimonio),
    CONSTRAINT fk_tb_exemplares_livro FOREIGN KEY (livro_id) REFERENCES tb_livros (id)
);

CREATE TABLE tb_emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exemplar_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    data_emprestimo DATE NOT NULL,
    data_prevista_devolucao DATE NOT NULL,
    data_devolucao DATE,
    data_encerramento DATE,
    situacao VARCHAR(255) NOT NULL,
    CONSTRAINT fk_tb_emprestimos_exemplar FOREIGN KEY (exemplar_id) REFERENCES tb_exemplares (id),
    CONSTRAINT fk_tb_emprestimos_usuario FOREIGN KEY (usuario_id) REFERENCES tb_cadastro (id)
);

CREATE TABLE tb_pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMERIC(38, 2) NOT NULL,
    data_pagamento DATE NOT NULL,
    emprestimo_id BIGINT NOT NULL,
    CONSTRAINT fk_tb_pagamentos_emprestimo FOREIGN KEY (emprestimo_id) REFERENCES tb_emprestimos (id)
);
